\set ON_ERROR_STOP on

BEGIN;

DO $$
DECLARE
    test_professional_id UUID;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind = 'r'
          AND c.relname IN ('specialties', 'professionals', 'specialty_seed_ownership'))
    THEN RAISE EXCEPTION 'Domain tables must not live in public'; END IF;

    IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind = 'r'
          AND c.relname NOT IN (
              'databasechangelog',
              'databasechangeloglock',
              'databasechangelog_professional_management',
              'databasechangeloglock_professional_management'
          ))
    THEN RAISE EXCEPTION 'Unexpected public tables exist'; END IF;

    IF to_regclass('professional_management.professional') IS NULL
    THEN RAISE EXCEPTION 'Expected the professional table'; END IF;

    -- DEC-005: every professional is a general practitioner; ddl-alter-020 drops
    -- the specialty catalog and its seed ownership ledger.
    IF to_regclass('professional_management.specialty') IS NOT NULL
       OR to_regclass('professional_management.specialty_seed_ownership') IS NOT NULL
    THEN RAISE EXCEPTION 'The specialty catalog must be gone after ddl-alter-020 (DEC-005)'; END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'professional_management_reader' AND NOT rolcanlogin) THEN
        RAISE EXCEPTION 'professional_management_reader NOLOGIN role is missing';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'professional_management_writer' AND NOT rolcanlogin) THEN
        RAISE EXCEPTION 'professional_management_writer NOLOGIN role is missing';
    END IF;
    IF NOT pg_has_role('professional_management_writer', 'professional_management_reader', 'MEMBER') THEN
        RAISE EXCEPTION 'professional_management_writer must inherit the reader role';
    END IF;
    IF NOT has_schema_privilege('professional_management_reader', 'professional_management', 'USAGE') THEN
        RAISE EXCEPTION 'professional_management_reader lacks USAGE on professional_management schema';
    END IF;
    IF NOT has_schema_privilege('professional_management_writer', 'professional_management', 'USAGE') THEN
        RAISE EXCEPTION 'professional_management_writer lacks USAGE on professional_management schema';
    END IF;
    IF NOT has_table_privilege('professional_management_reader', 'professional_management.professional', 'SELECT') THEN
        RAISE EXCEPTION 'professional_management_reader lacks SELECT on professional';
    END IF;
    IF has_table_privilege('professional_management_reader', 'professional_management.professional', 'INSERT') THEN
        RAISE EXCEPTION 'professional_management_reader unexpectedly has INSERT on professional';
    END IF;
    IF NOT has_table_privilege('professional_management_writer', 'professional_management.professional', 'SELECT,INSERT,UPDATE,DELETE') THEN
        RAISE EXCEPTION 'professional_management_writer lacks CRUD privileges on professional';
    END IF;
    -- DEC-006: identifiers are UUID. professional.id is generated by the
    -- database, so the table owns no sequence any more.
    IF (SELECT COUNT(*) FROM information_schema.columns
        WHERE table_schema = 'professional_management' AND table_name = 'professional'
          AND column_name = 'id' AND data_type = 'uuid' AND is_nullable = 'NO'
          AND column_default = 'gen_random_uuid()') <> 1
    THEN RAISE EXCEPTION 'Expected professional.id uuid NOT NULL DEFAULT gen_random_uuid() (DEC-006)'; END IF;
    IF pg_get_serial_sequence('professional_management.professional', 'id') IS NOT NULL
    THEN RAISE EXCEPTION 'professional.id must not own a sequence after ddl-alter-024'; END IF;
    IF (SELECT COUNT(*) FROM information_schema.columns
        WHERE table_schema = 'professional_management' AND table_name = 'professional'
          AND column_name = 'identity_user_id' AND data_type = 'uuid' AND is_nullable = 'NO') <> 1
    THEN RAISE EXCEPTION 'Expected professional.identity_user_id uuid NOT NULL (DEC-006)'; END IF;
    IF (SELECT COUNT(*) FROM information_schema.columns
        WHERE table_schema = 'professional_management' AND table_name = 'idempotency_key'
          AND column_name = 'professional_id' AND data_type = 'uuid' AND is_nullable = 'NO') <> 1
    THEN RAISE EXCEPTION 'Expected idempotency_key.professional_id uuid NOT NULL (DEC-006)'; END IF;
    IF (SELECT COUNT(*) FROM information_schema.columns
        WHERE table_schema = 'professional_management'
          AND column_name IN ('id_uuid', 'identity_user_id_uuid', 'professional_id_uuid')) <> 0
    THEN RAISE EXCEPTION 'The expand columns of ddl-alter-022 must be gone after ddl-alter-024'; END IF;
    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conrelid = 'professional_management.professional'::regclass
          AND conname = 'pk_professionals' AND contype = 'p') <> 1
    THEN RAISE EXCEPTION 'Expected pk_professionals on the uuid id'; END IF;
    IF (SELECT COUNT(*) FROM pg_indexes
        WHERE schemaname = 'professional_management' AND tablename = 'idempotency_key'
          AND indexname = 'idx_idempotency_key_professional_id'
          AND indexdef ILIKE '%(professional_id)%') <> 1
    THEN RAISE EXCEPTION 'Expected idx_idempotency_key_professional_id on the uuid column'; END IF;

    EXECUTE 'CREATE TABLE professional_management.grant_default_probe (id integer)';
    IF NOT has_table_privilege('professional_management_reader', 'professional_management.grant_default_probe', 'SELECT')
       OR has_table_privilege('professional_management_reader', 'professional_management.grant_default_probe', 'INSERT')
       OR NOT has_table_privilege('professional_management_writer', 'professional_management.grant_default_probe', 'SELECT,INSERT,UPDATE,DELETE') THEN
        RAISE EXCEPTION 'Default table privileges were not applied to a new table';
    END IF;
    EXECUTE 'CREATE SEQUENCE professional_management.grant_default_probe_seq';
    IF NOT has_sequence_privilege('professional_management_writer', 'professional_management.grant_default_probe_seq', 'USAGE') THEN
        RAISE EXCEPTION 'Default sequence privileges were not applied to a new sequence';
    END IF;
    EXECUTE 'DROP SEQUENCE professional_management.grant_default_probe_seq';
    EXECUTE 'DROP TABLE professional_management.grant_default_probe';

    IF EXISTS (SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'professional_management' AND table_name = 'professional'
          AND column_name = 'specialty_id')
    THEN RAISE EXCEPTION 'professional.specialty_id must be gone after ddl-alter-019 (DEC-005)'; END IF;

    -- ddl-alter-021: professional_type is required and defaults to the only value.
    IF (SELECT COUNT(*) FROM information_schema.columns
        WHERE table_schema = 'professional_management' AND table_name = 'professional'
          AND column_name = 'professional_type' AND data_type = 'text'
          AND is_nullable = 'NO'
          AND column_default = '''GENERAL_PRACTITIONER''::text') <> 1
    THEN RAISE EXCEPTION 'Expected professional.professional_type text NOT NULL DEFAULT GENERAL_PRACTITIONER'; END IF;

    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conrelid = 'professional_management.professional'::regclass
          AND conname = 'chk_professionals_professional_type_length' AND contype = 'c' AND convalidated) <> 1
    THEN RAISE EXCEPTION 'Expected chk_professionals_professional_type_length CHECK'; END IF;

    IF (SELECT COUNT(*) FROM information_schema.columns
        WHERE table_schema = 'professional_management' AND table_name = 'professional'
          AND column_name = 'status' AND data_type = 'text'
          AND is_nullable = 'NO') <> 1
    THEN RAISE EXCEPTION 'Expected professional.status text NOT NULL'; END IF;

    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conrelid = 'professional_management.professional'::regclass
          AND conname = 'chk_professionals_status_length' AND contype = 'c' AND convalidated) <> 1
    THEN RAISE EXCEPTION 'Expected chk_professionals_status_length CHECK'; END IF;

    IF (SELECT column_default FROM information_schema.columns
        WHERE table_schema = 'professional_management' AND table_name = 'professional'
          AND column_name = 'status') <> '''ACTIVE''::text'
    THEN RAISE EXCEPTION 'Expected professional.status DEFAULT ACTIVE'; END IF;

    IF (SELECT COUNT(*) FROM information_schema.columns
        WHERE table_schema = 'professional_management' AND table_name = 'professional'
          AND column_name IN ('active', 'is_active', 'deleted_at')) <> 0
    THEN RAISE EXCEPTION 'Unexpected professional lifecycle columns exist'; END IF;

    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conrelid = 'professional_management.professional'::regclass
          AND conname = 'chk_professionals_years_experience_nonnegative' AND contype = 'c' AND convalidated) <> 1
    THEN RAISE EXCEPTION 'Expected validated nonnegative years_experience CHECK constraint'; END IF;

    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conrelid = 'professional_management.professional'::regclass
          AND conname = 'chk_professionals_professional_type' AND contype = 'c' AND convalidated
          AND pg_get_constraintdef(oid) ILIKE '%GENERAL_PRACTITIONER%'
          AND pg_get_constraintdef(oid) NOT ILIKE '%SPECIALIST%') <> 1
    THEN RAISE EXCEPTION 'Expected a validated professional_type CHECK that allows only GENERAL_PRACTITIONER'; END IF;

    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conrelid = 'professional_management.professional'::regclass
          AND conname = 'chk_professionals_status' AND contype = 'c' AND convalidated) <> 1
    THEN RAISE EXCEPTION 'Expected validated status CHECK constraint'; END IF;

    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conname = 'uq_professionals_identity_user_id' AND contype = 'u') <> 1
    THEN RAISE EXCEPTION 'Expected uq_professionals_identity_user_id'; END IF;

    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conname = 'uq_professionals_license_number' AND contype = 'u') <> 1
    THEN RAISE EXCEPTION 'Expected uq_professionals_license_number'; END IF;

    -- With the catalog gone, professional references no other table; its
    -- account reference to Identity & Access is external and has no FK.
    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conrelid = 'professional_management.professional'::regclass AND contype = 'f') <> 0
    THEN RAISE EXCEPTION 'professional must not have foreign keys after ddl-alter-019'; END IF;

    IF (SELECT COUNT(*) FROM pg_indexes
        WHERE schemaname = 'professional_management' AND tablename = 'professional'
          AND indexname = 'idx_professional_specialty_id') <> 0
    THEN RAISE EXCEPTION 'The specialty_id index must be gone with its column'; END IF;

    IF (SELECT COUNT(*) FROM pg_index i
        JOIN pg_attribute a ON a.attrelid = i.indrelid
                           AND a.attname = 'status'
                           AND a.attnum = ANY(i.indkey)
        WHERE i.indrelid = 'professional_management.professional'::regclass AND i.indisvalid) <> 1
       OR (SELECT COUNT(*) FROM pg_indexes
           WHERE schemaname = 'professional_management' AND tablename = 'professional'
             AND indexname = 'idx_professional_status'
             AND indexdef ILIKE '%(status)%') <> 1
    THEN RAISE EXCEPTION 'Expected exactly one status index named idx_professional_status'; END IF;

    -- The UNIQUE constraints renamed by ddl-alter-010 must still reject
    -- duplicates. Each block raises a plain exception when the insert is
    -- wrongly accepted; only unique_violation is swallowed, so an accepted
    -- duplicate fails the run instead of passing silently.
    INSERT INTO professional_management.professional
        (identity_user_id, license_number, years_experience)
    VALUES ('b0000000-0000-4000-8000-000000000991', 'DUP-LICENSE', 0);

    BEGIN
        INSERT INTO professional_management.professional
            (identity_user_id, license_number, years_experience)
        VALUES ('b0000000-0000-4000-8000-000000000992', 'DUP-LICENSE', 0);
        RAISE EXCEPTION 'Duplicate license_number should be rejected';
    EXCEPTION WHEN unique_violation THEN NULL;
    END;

    BEGIN
        INSERT INTO professional_management.professional
            (identity_user_id, license_number, years_experience)
        VALUES ('b0000000-0000-4000-8000-000000000991', 'DUP-IDENTITY', 0);
        RAISE EXCEPTION 'Duplicate identity_user_id should be rejected';
    EXCEPTION WHEN unique_violation THEN NULL;
    END;

    DELETE FROM professional_management.professional WHERE license_number = 'DUP-LICENSE';
    IF EXISTS (SELECT 1 FROM professional_management.professional
               WHERE license_number = 'DUP-LICENSE' OR identity_user_id = 'b0000000-0000-4000-8000-000000000991')
    THEN RAISE EXCEPTION 'Rejected duplicates must not create a professional'; END IF;

    -- DEC-005: an insert that omits the lifecycle fields registers an ACTIVE
    -- general practitioner, the profile the API creates.
    INSERT INTO professional_management.professional
        (identity_user_id, license_number, years_experience)
    VALUES ('b0000000-0000-4000-8000-000000000002', 'TEST-API-INSERT-001', 0);
    IF NOT EXISTS (SELECT 1 FROM professional_management.professional
                   WHERE license_number = 'TEST-API-INSERT-001'
                     AND professional_type = 'GENERAL_PRACTITIONER' AND status = 'ACTIVE')
    THEN RAISE EXCEPTION 'An insert without lifecycle fields must default to an ACTIVE GENERAL_PRACTITIONER'; END IF;

    UPDATE professional_management.professional SET status = 'INACTIVE'
    WHERE license_number = 'TEST-API-INSERT-001';
    IF NOT EXISTS (SELECT 1 FROM professional_management.professional
                   WHERE license_number = 'TEST-API-INSERT-001' AND status = 'INACTIVE')
    THEN RAISE EXCEPTION 'Expected the allowed status values'; END IF;
    UPDATE professional_management.professional SET status = 'ACTIVE'
    WHERE license_number = 'TEST-API-INSERT-001';

    BEGIN
        UPDATE professional_management.professional SET professional_type = 'SPECIALIST'
        WHERE license_number = 'TEST-API-INSERT-001';
        RAISE EXCEPTION 'SPECIALIST must be rejected (DEC-005)';
    EXCEPTION WHEN check_violation THEN NULL;
    END;

    BEGIN
        UPDATE professional_management.professional SET professional_type = NULL
        WHERE license_number = 'TEST-API-INSERT-001';
        RAISE EXCEPTION 'A missing professional_type must be rejected';
    EXCEPTION WHEN not_null_violation THEN NULL;
    END;

    BEGIN
        UPDATE professional_management.professional SET professional_type = 'INVALID'
        WHERE license_number = 'TEST-API-INSERT-001';
        RAISE EXCEPTION 'Invalid professional_type should be rejected';
    EXCEPTION WHEN check_violation THEN NULL;
    END;

    BEGIN
        UPDATE professional_management.professional SET status = 'PENDING'
        WHERE license_number = 'TEST-API-INSERT-001';
        RAISE EXCEPTION 'Invalid status should be rejected';
    EXCEPTION WHEN check_violation THEN NULL;
    END;

    DELETE FROM professional_management.professional WHERE license_number = 'TEST-API-INSERT-001';

    IF to_regclass('professional_management.idempotency_key') IS NULL THEN
        RAISE EXCEPTION 'Expected table professional_management.idempotency_key';
    END IF;

    IF (SELECT COUNT(*) FROM pg_constraint WHERE conname = 'pk_idempotency_key' AND contype = 'p') <> 1 THEN
        RAISE EXCEPTION 'Expected primary key pk_idempotency_key';
    END IF;

    IF (SELECT COUNT(*) FROM pg_constraint WHERE conname = 'fk_idempotency_key_professional' AND contype = 'f' AND confdeltype = 'c') <> 1 THEN
        RAISE EXCEPTION 'Expected foreign key fk_idempotency_key_professional with ON DELETE CASCADE';
    END IF;

    -- ddl-alter-017 re-declares this FK from 04_alter with NOT VALID and
    -- ddl-alter-018 validates it, so the constraint must be marked validated
    -- after a full update: convalidated = false would mean the expand half ran
    -- without its contract half and orphan rows are still unchecked.
    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE conrelid = 'professional_management.idempotency_key'::regclass
          AND conname = 'fk_idempotency_key_professional'
          AND contype = 'f'
          AND convalidated = true
          AND confrelid = 'professional_management.professional'::regclass
          AND pg_get_constraintdef(oid) ILIKE '%ON DELETE CASCADE%') <> 1 THEN
        RAISE EXCEPTION 'Expected validated fk_idempotency_key_professional with ON DELETE CASCADE';
    END IF;

    IF (SELECT COUNT(*) FROM information_schema.columns
        WHERE table_schema = 'professional_management'
          AND table_name = 'idempotency_key'
          AND column_name = 'request_hash'
          AND data_type = 'text'
          AND is_nullable = 'YES') <> 1 THEN
        RAISE EXCEPTION 'Expected nullable text column professional_management.idempotency_key.request_hash';
    END IF;

    IF NOT has_table_privilege('professional_management_reader', 'professional_management.idempotency_key', 'SELECT') THEN
        RAISE EXCEPTION 'professional_management_reader lacks SELECT on idempotency_key';
    END IF;

    IF NOT has_table_privilege('professional_management_writer', 'professional_management.idempotency_key', 'INSERT') THEN
        RAISE EXCEPTION 'professional_management_writer lacks INSERT on idempotency_key';
    END IF;

    -- A real professional is required so that the key length CHECK is the only
    -- constraint that can reject the negative cases below. Inserting a NULL
    -- professional_id would be refused by the NOT NULL constraint instead, and
    -- the test would pass without ever exercising chk_idempotency_key_length.
    INSERT INTO professional_management.professional
        (identity_user_id, license_number, years_experience)
    VALUES ('b0000000-0000-4000-8000-000000000999', 'TEST-IDEMP-LEN', 0);

    SELECT id INTO test_professional_id FROM professional_management.professional
    WHERE license_number = 'TEST-IDEMP-LEN';

    IF test_professional_id IS NULL THEN
        RAISE EXCEPTION 'Expected a test professional for the idempotency_key length checks';
    END IF;

    -- CHECK length: reject keys shorter than 8 characters
    BEGIN
        INSERT INTO professional_management.idempotency_key (key, professional_id)
        VALUES ('1234567', test_professional_id);
        RAISE EXCEPTION 'CHECK should reject a 7-char key';
    EXCEPTION
        WHEN check_violation THEN NULL;
    END;

    -- CHECK length: reject keys longer than 128 characters
    BEGIN
        INSERT INTO professional_management.idempotency_key (key, professional_id)
        VALUES (repeat('x', 129), test_professional_id);
        RAISE EXCEPTION 'CHECK should reject a 129-char key';
    EXCEPTION
        WHEN check_violation THEN NULL;
    END;

    -- Boundary values 8 and 128 characters are accepted
    INSERT INTO professional_management.idempotency_key (key, professional_id)
    VALUES ('12345678', test_professional_id);
    INSERT INTO professional_management.idempotency_key (key, professional_id)
    VALUES (repeat('x', 128), test_professional_id);

    IF NOT EXISTS (SELECT 1 FROM professional_management.idempotency_key
                   WHERE professional_id = test_professional_id)
    THEN RAISE EXCEPTION 'Boundary-length keys must be accepted'; END IF;

    -- Cleanup. A CASCADE delete also proves the FK really cascades.
    DELETE FROM professional_management.professional WHERE license_number = 'TEST-IDEMP-LEN';
    IF EXISTS (SELECT 1 FROM professional_management.idempotency_key
               WHERE professional_id = test_professional_id)
    THEN RAISE EXCEPTION 'idempotency_key rows must be removed by ON DELETE CASCADE'; END IF;

    -- The suffix assertion applies by default. The databases it must
    -- NOT run against are the seed rollback integration test's
    -- fixtures (`seed_<variant>_<hash>`), which deliberately create the
    -- unsuffixed `databasechangelog` from legacy changelogs to test
    -- legacy compatibility. Any other database name — the normal CI
    -- fixture, the shared instance, a future test harness — gets the
    -- assertion by default, so a regression into unsuffixed control
    -- tables cannot slip through silently.
    IF current_database() NOT LIKE 'seed_%' THEN
        IF (SELECT COUNT(*) FROM information_schema.tables
            WHERE table_name IN (
                'databasechangelog_professional_management',
                'databasechangeloglock_professional_management'
            )) <> 2 THEN
            RAISE EXCEPTION 'Expected domain-suffixed Liquibase control tables';
        END IF;
    END IF;

    -- Simulate re-application of the role changeset against a database
    -- where the roles already exist. This exercises the no-op branch
    -- of the idempotent DO block added in PR #26.
    DO $inner$
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'professional_management_reader') THEN
            CREATE ROLE professional_management_reader NOLOGIN;
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'professional_management_writer') THEN
            CREATE ROLE professional_management_writer NOLOGIN;
        END IF;
    END
    $inner$;

    -- Both roles must still exist after the second application.
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'professional_management_reader') THEN
        RAISE EXCEPTION 'reader role was dropped during re-application';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'professional_management_writer') THEN
        RAISE EXCEPTION 'writer role was dropped during re-application';
    END IF;

    -- Exercise the membership-detection query used by the rollback of
    -- 001-create-roles. The rollback decides whether to drop the
    -- reader/writer roles based on whether either role has any member
    -- other than the nested reader->writer pair. That detection branch
    -- is critical (it decides a destructive DROP ROLE) and must not
    -- remain untested.
    --
    -- This test does NOT run the rollback (that would drop roles the
    -- other tests depend on). It replicates the detection query against
    -- a simulated "shared instance" state — a fake external role granted
    -- the writer role — and asserts the query returns true. If that
    -- detection ever regresses, this assertion fails and the destructive
    -- path would be caught before merge.
    DO $rollback_probe$
    DECLARE
        reader_has_external_members boolean;
        writer_has_external_members boolean;
        would_drop_roles boolean;
    BEGIN
        -- Simulate infra's app user being granted the writer role.
        EXECUTE 'CREATE ROLE test_external_app_probe NOLOGIN';
        EXECUTE 'GRANT professional_management_writer TO test_external_app_probe';

        SELECT EXISTS (
            SELECT 1 FROM pg_auth_members m
            JOIN pg_roles r ON r.oid = m.roleid
            WHERE r.rolname = 'professional_management_reader'
              AND NOT EXISTS (
                SELECT 1 FROM pg_roles rr
                WHERE rr.oid = m.member
                  AND rr.rolname = 'professional_management_writer'
              )
        ) INTO reader_has_external_members;

        SELECT EXISTS (
            SELECT 1 FROM pg_auth_members m
            JOIN pg_roles r ON r.oid = m.roleid
            WHERE r.rolname = 'professional_management_writer'
        ) INTO writer_has_external_members;

        would_drop_roles := NOT reader_has_external_members AND NOT writer_has_external_members;

        -- Cleanup before assertions so the fake role never leaks if the
        -- assertion below raises.
        EXECUTE 'REVOKE professional_management_writer FROM test_external_app_probe';
        EXECUTE 'DROP ROLE test_external_app_probe';

        -- Now assert on the captured value.
        IF would_drop_roles THEN
            RAISE EXCEPTION 'Rollback membership detection failed to see the writer role as having an external member; the rollback would incorrectly drop the roles on the shared instance';
        END IF;
    END
    $rollback_probe$;
END;
$$;

ROLLBACK;
